/* AUTO VIDEO MAKER — project/output library. */
window.VIEWS = window.VIEWS || {};

VIEWS.projects = {
  title: "Projects",
  render: async function () {
    var projects = await API.getProjectsWithFallback();
    if (!projects.length) {
      return '<div class="page-head"><div><p class="eyebrow">Execution outputs</p><h1 class="page-title">Projects</h1><p class="page-sub">Projects are execution outputs. They are not production intent and are never adopted automatically.</p></div><div class="head-actions"><a class="btn btn-primary" href="#/create">' + ICONS.create + ' Create Video</a></div></div>' +
        '<div class="card cc-state-panel">' + COMPONENTS.emptyState("film", "No projects yet", "Video projects generated by the AVM engine will appear here.", '<a class="btn btn-primary" href="#/create">Create Video</a>') + '</div>';
    }
    return '<div class="page-head"><div><p class="eyebrow">Execution outputs</p><h1 class="page-title">Projects</h1><p class="page-sub">Review existing project artifacts and publication records. Binding is shown only when the authoritative manifest provides it.</p></div><div class="head-actions"><a class="btn btn-primary" href="#/create">' + ICONS.create + ' Create Video</a></div></div>' +
      (!API.live ? '<p class="demo-notice"><span class="sample-tag">Demo data</span> Real projects are unavailable while the engine is offline.</p>' : '') +
      '<div class="grid grid-3">' + projects.map(COMPONENTS.projectCard).join("") + '</div>';
  }
};