def test_arbitrary_and_internal_plan_fields_are_never_returned(monkeypatch, tmp_path):
    env = _seam(monkeypatch, tmp_path)
    # An unknown extra field on disk is ignored by the model, so an explicit
    # allow-list projection is the only thing that can keep it out of the API.
    directory = _plan_dir(env["productions"])
    plan_path = directory / "production_plan.json"
    raw = json.loads(plan_path.read_text(encoding="utf-8"))
    raw["surprise"] = "SURPRISE-LEAK"
    raw["metadata"]["note"] = "NOTE-LEAK"
    plan_path.write_text(json.dumps(raw), encoding="utf-8")
    meta_path = directory / "plan_meta.json"
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    meta["content_hash"] = compute_content_hash(plan_path)
    meta_path.write_text(json.dumps(meta), encoding="utf-8")

    status, payload = web.unit_plan_payload(PID, UNIT_ID)
    serialized = json.dumps(payload)

    assert status == 200
    for forbidden_key in (
        "project_id", "metadata", "provider", "model", "content_hash",
        "plan_identity", "path", "safe_path", "plan_directory", "transition",
        "on_screen_text", "visual_style", "camera_direction", "sound_design",
        "visual_source", "requires_fact_check", "planning_constraints",
        "planner_warnings", "generated_at", "route_compilation",
    ):
        assert f'"{forbidden_key}"' not in serialized, forbidden_key
    for marker in LEAK_MARKERS + ("NOTE-LEAK",):
        assert marker not in serialized, marker


