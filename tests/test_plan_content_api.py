"""G5 — plan / script CONTENT read API
(``GET /api/productions/{id}/units/{uid}/plan``).

The creative plan content was ALREADY durable and hash-pinned before this task
(``productions/<pid>/units/<uid>/plan/production_plan.json`` +
``plan_meta.json`` + the production binding); G5 only adds the read projection.
These tests pin exactly that:

- the endpoint returns the allow-listed CREATIVE content and nothing else;
- planner provenance, route-compilation evidence, scene provenance and
  accounting stay OUTSIDE the plan content;
- content is validated (the real ``ProductionPlan`` model + the recorded
  SHA-256) before it is served, and a plan that contradicts its hash, identity
  or binding is refused loudly instead of being served, repaired or regenerated;
- a unit with no plan yet is an honest NOT_GENERATED (never fabricated, never
  generated by a GET);
- every read is strictly non-mutating;
- the list/detail/progress paths never read a plan body (Phase 2B performance).

Hermetic: no provider is constructed, no network call is made, no plan is
generated by a GET, and no billable production runs.
"""

