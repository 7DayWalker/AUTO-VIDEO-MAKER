class _StubPlanner:
    """Deterministic planner; records calls so GET-side generation is provable."""

    def __init__(self, plan):
        self._plan = plan
        self.calls = []

    def plan(self, brief):
        self.calls.append(brief)
        return ContentGenerationResult.from_plan(
            self._plan, provider=PLANNER_PROVIDER, model=PLANNER_MODEL
        )


class _ProjectInitializingEngine:
    """Runs ONLY the real project-initialization seam (no stages, no media)."""

    def __init__(self, config):
        self.config = config
        self.manifest = None

    def run(self):
        orchestrator = pipeline_module.ProductionOrchestrator(self.config)
        orchestrator._initialize_project()
        orchestrator._save_manifest()
        self.manifest = orchestrator.manifest
        return self.manifest


def _tree_bytes(root: Path) -> dict:
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


def _isolate(monkeypatch, tmp_path):
    productions = tmp_path / "productions"
    projects = tmp_path / "projects"
    monkeypatch.setattr(web, "PRODUCTIONS_DIR", productions)
    monkeypatch.setattr(web, "PROJECTS_DIR", projects)
    monkeypatch.setattr(web, "_production_runs", {})
    monkeypatch.setattr(pipeline_module, "ORCHESTRATOR_OUTPUT_DIR", projects)
    monkeypatch.setattr(
        pipeline_module, "ORCHESTRATOR_LOGS_DIR", tmp_path / "logs"
    )
    return productions, projects


def _plan_dir(productions: Path, unit_id: str = UNIT_ID) -> Path:
    return unit_plan_dir(PID, unit_id, root=productions)


def _seam(monkeypatch, tmp_path, *, bind=False, route=None, strategy=None, name=None):
    """Create REAL plan artifacts through the REAL executor seams.

    ``bind=True`` additionally runs the execution seam so the unit gets a real
    ``ProjectManifest.production_binding`` (with its recorded content hash),
    a project-side plan copy, and G3 route-compilation evidence.
    """
    if name:
        tmp_path = tmp_path / name
    productions, projects = _isolate(monkeypatch, tmp_path)
    production = make_production()
    updates = {}
    if route is not None:
        updates["route"] = route
    if strategy is not None:
        updates["generation_strategy"] = strategy
    if updates:
        production = production.model_copy(update=updates)
    save_new_production(production, root=productions)
    plan = make_plan()
    planner = _StubPlanner(plan)

    base = OrchestratorConfig(
        topic="Plan content",
        mock_mode=not bind,
        visual_mode="local",
        visual_default_provider="image_motion",
        image_source="auto",
    )
    engines = []

    def factory(config):
        engine = _ProjectInitializingEngine(config)
        engines.append(engine)
        return engine

    executor = ProductionExecutor(
        PID,
        productions_root=productions,
        projects_root=projects,
        base_config=base,
        planner_factory=lambda: planner,
        orchestrator_factory=factory,
    )
    if bind:
        executor.execute()
    else:
        executor.resolve_plan(executor.load(), executor.load().units[0])
    return {
        "productions": productions,
        "projects": projects,
        "executor": executor,
        "plan": plan,
        "planner": planner,
        "engines": engines,
    }


