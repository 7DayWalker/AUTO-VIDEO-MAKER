ABSOLUTE_PATH_PATTERN = re.compile(r"[a-zA-Z]:[\\/]|\\\\|[\\/]Users[\\/]")


def _plan_path(env) -> Path:
    return _plan_dir(env["productions"]) / "production_plan.json"


def _meta_path(env) -> Path:
    return _plan_dir(env["productions"]) / "plan_meta.json"


def _resync_meta(env) -> None:
    """Rewrite plan_meta.json so its recorded hash matches the current bytes."""
    meta = json.loads(_meta_path(env).read_text("utf-8"))
    meta["content_hash"] = compute_content_hash(_plan_path(env))
    _meta_path(env).write_text(json.dumps(meta), encoding="utf-8")


def test_hash_mismatch_is_rejected_and_nothing_is_served(monkeypatch, tmp_path):
    env = _seam(monkeypatch, tmp_path)
    original = _plan_path(env).read_bytes()
    # Whitespace-only change: still valid JSON, so ONLY the hash can catch it.
    _plan_path(env).write_bytes(original + b"\n")

    status, payload = web.unit_plan_payload(PID, UNIT_ID)
    serialized = json.dumps(payload)

    assert status == 500
    assert payload["error"] == "PLAN_EVIDENCE_INVALID"
    assert payload["available"] is False
    assert "hash" in payload["message"]
    assert "plan" not in payload  # no partial content is ever handed back
    assert SCRIPT not in serialized
    # A refusal never repairs or rewrites the durable artifact.
    assert _plan_path(env).read_bytes() == original + b"\n"


