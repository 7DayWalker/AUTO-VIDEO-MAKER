def test_rejections_never_leak_paths_or_plan_content(monkeypatch, tmp_path):
    bound = _seam(monkeypatch, tmp_path, name="bound", bind=True)
    _plan_path(bound).write_bytes(_plan_path(bound).read_bytes() + b"\n")
    payloads = [web.unit_plan_payload(PID, UNIT_ID)]

    plain = _seam(monkeypatch, tmp_path, name="plain")
    _meta_path(plain).write_text("{oops", encoding="utf-8")
    payloads.append(web.unit_plan_payload(PID, UNIT_ID))

    unparsable = _seam(monkeypatch, tmp_path, name="unparsable")
    _plan_path(unparsable).write_text("{ still not json", encoding="utf-8")
    _resync_meta(unparsable)  # hash now matches the corrupted bytes
    payloads.append(web.unit_plan_payload(PID, UNIT_ID))

    for status, payload in payloads:
        serialized = json.dumps(payload)
        assert status == 500
        assert not ABSOLUTE_PATH_PATTERN.search(serialized), serialized
        assert "production_plan.json" not in serialized
        assert "plan_meta.json" not in serialized
        assert "units/" not in serialized
        assert SCRIPT not in serialized


